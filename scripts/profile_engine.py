"""V-5: profile the event engine (PLAN §3.7); writes ``reports/profile.html`` and
``reports/profile.md``.

Usage: ``uv run python tasks.py profile``. The panel is synthetic with the real shape
(correction C16): 49 assets and as many bars as there are weekdays from 1926-07-01 to
2026-09-30. It ends on 2005-12-30, because the data handler's vault drops rows from 2006 on.
Run time does not depend on the values. B3 and B4 run at 10 bp; each is timed plainly, once
under pyinstrument (time share per component) and once under tracemalloc (peak memory).
Hypothetical backtests, not investment advice.
"""

from __future__ import annotations

import platform
import sys
import time
import tracemalloc
from collections import defaultdict
from typing import Any

import numpy as np
import pandas as pd
from pyinstrument import Profiler

from momlab import engine, paths
from momlab.config import RunConfig
from momlab.data.handler import DataHandler

TARGET_SECONDS = 30.0
N_ASSETS = 49
COMPONENTS = {
    "data/handler.py": "data handler / AsOfView",
    "data/calendar.py": "calendar",
    "portfolio.py": "portfolio",
    "execution.py": "execution",
    "costs.py": "costs",
    "signals/rules.py": "signals",
    "risk.py": "risk",
    "queue.py": "events and queue",
    "events.py": "events and queue",
    "engine.py": "engine loop",
}


def panel() -> tuple[pd.DatetimeIndex, list[str], np.ndarray]:
    """Synthetic panel with the real number of bars (C16)."""
    n_bars = len(pd.bdate_range("1926-07-01", "2026-09-30"))
    dates = pd.bdate_range(end="2005-12-30", periods=n_bars)
    rets = np.random.default_rng(2026).normal(0.0003, 0.01, (n_bars, N_ASSETS))
    return dates, [f"S{i:02d}" for i in range(N_ASSETS)], rets


def _component(path: str | None) -> str | None:
    if not path:
        return None
    p = path.replace("\\", "/")
    if "/momlab/" not in p:
        return None
    return COMPONENTS.get(p.split("/momlab/", 1)[1], "other momlab")


def component_shares(root: Any) -> dict[str, float]:
    """Self time per component; time in NumPy, pandas or builtins goes to the nearest
    momlab caller."""
    shares: dict[str, float] = defaultdict(float)
    stack = [(root, "outside momlab")]
    while stack:
        frame, current = stack.pop()
        comp = _component(frame.file_path) or current
        st = frame.total_self_time
        shares[comp] += st() if callable(st) else st
        stack.extend((child, comp) for child in frame.children)
    total = sum(shares.values())
    return {k: v / total for k, v in sorted(shares.items(), key=lambda kv: -kv[1])}


def main() -> int:
    """Profile B3 and B4 and write the reports; exit 1 if a run misses the 30 s target."""
    dates, assets, rets = panel()
    rows, shares_by = [], {}
    for strategy in ("b3", "b4"):
        cfg = RunConfig(
            strategy=strategy,
            start=dates[0].date(),
            end=dates[-1].date(),
            cost={"model": "flat", "bps": 10.0},
        )
        t0 = time.perf_counter()
        engine.run(cfg, DataHandler(dates, assets, rets))
        wall = time.perf_counter() - t0

        profiler = Profiler(interval=0.001)
        profiler.start()
        engine.run(cfg, DataHandler(dates, assets, rets))
        session = profiler.stop()
        shares_by[strategy] = component_shares(session.root_frame())
        if strategy == "b4":
            out = paths.REPORTS_DIR / "profile.html"
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(profiler.output_html(), encoding="utf-8")

        tracemalloc.start()
        engine.run(cfg, DataHandler(dates, assets, rets))
        _, peak = tracemalloc.get_traced_memory()
        tracemalloc.stop()
        rows.append((strategy.upper(), len(dates), wall, len(dates) / wall, peak / 2**20))

    ok = all(r[2] < TARGET_SECONDS for r in rows)
    comps = sorted(
        {c for s in shares_by.values() for c in s}, key=lambda c: -shares_by["b4"].get(c, 0)
    )
    lines = [
        "# Engine performance profile",
        "",
        "Generated by `scripts/profile_engine.py` (task V-5, PLAN §3.7). Synthetic panel with the",
        f"real shape: {N_ASSETS} assets × {len(dates)} bars "
        "(the weekdays of 1926-07-01 … 2026-09-30),",
        "dated to end 2005-12-30 (C16). B3 and B4 at 10 bp. Hypothetical backtests.",
        "",
        f"Machine: {platform.platform()}, Python {platform.python_version()}, "
        f"{platform.processor() or 'unknown CPU'}.",
        "",
        "| Strategy | Bars | Wall time (s) | Bars per second | Peak memory (MiB, tracemalloc) |",
        "|---|---|---|---|---|",
    ]
    lines += [f"| {s} | {n} | {w:.2f} | {b:,.0f} | {m:.1f} |" for s, n, w, b, m in rows]
    lines += [
        "",
        f"Target < {TARGET_SECONDS:g} s per full backtest: **{'met' if ok else 'MISSED'}**.",
        "",
        "## Time share per component (pyinstrument, 1 ms sampling)",
        "",
        "Self time is attributed to the nearest momlab module on the call stack, so NumPy and",
        "pandas work done for the portfolio counts as portfolio time.",
        "",
        "| Component | B3 | B4 |",
        "|---|---|---|",
    ]
    lines += [
        f"| {c} | {shares_by['b3'].get(c, 0):.1%} | {shares_by['b4'].get(c, 0):.1%} |"
        for c in comps
    ]
    lines += ["", "Call tree for B4: `reports/profile.html`.", ""]
    md = paths.REPORTS_DIR / "profile.md"
    md.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("\n".join(lines))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
