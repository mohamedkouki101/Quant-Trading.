"""V-3: engine vs bt 1.4.1 on a synthetic market; writes ``reports/crosscheck.md``.

Usage: ``uv run python scripts/v3_crosscheck.py``. Every number in the report is printed by
this script. Synthetic data only; the real-data check (research period) runs in
``tests/crosscheck/test_bt.py`` once the ``prereg-v1`` tag exists (C17).
Hypothetical backtests, not investment advice.
"""

from __future__ import annotations

import sys
import warnings

from momlab import crosscheck, paths, synthetic
from momlab.config import RunConfig

SEED = 2026
TOL_ANN_BP = 5.0
TOL_CORR = 0.9999
COLUMNS = (
    "Strategy",
    "Cost (bp)",
    "bt weights dated",
    "Days",
    "Ann. gap (bp/yr)",
    "Daily corr",
    "Max daily gap",
    "Max weight vs target",
    "bt vs replica: max daily gap",
    "bt vs replica: max weight gap",
)


def main() -> int:
    """Run the grid, write the report and return 1 if the zero-cost tolerance is missed."""
    warnings.simplefilter("ignore")
    m = synthetic.null_market(n_assets=49, n_years=30, seed=SEED)
    rows = []
    ok = True
    for strategy in ("b1", "b3", "b4"):
        for bps in (0.0, 10.0, 50.0):
            cfg = RunConfig(
                strategy=strategy,
                start=m.dates[0].date(),
                end=m.dates[-1].date(),
                cost={"model": "flat", "bps": bps},
            )
            c = crosscheck.bt_crosscheck(cfg, m)
            if bps == 0.0:
                ok &= abs(c.ann_gap_bp) < TOL_ANN_BP and c.corr > TOL_CORR
            rows.append((strategy.upper(), f"{bps:g}", "fill date", c))
    cfg = RunConfig(
        strategy="b3",
        start=m.dates[0].date(),
        end=m.dates[-1].date(),
        cost={"model": "flat", "bps": 0.0},
    )
    rows.append(
        ("B3", "0", "order date (unshifted)", crosscheck.bt_crosscheck(cfg, m, shift=False))
    )

    lines = [
        "# Engine vs bt 1.4.1 cross-check",
        "",
        "Hypothetical backtest on synthetic data, not investment advice. Generated by",
        "`scripts/v3_crosscheck.py` (task V-3, PLAN §9.3 step 2).",
        "",
        f"Market: `synthetic.null_market(n_assets=49, n_years=30, seed={SEED})`, 1950–1979,",
        "i.i.d. Student-t daily returns, RF = 0 (bt's cash earns nothing). Engine targets are fed",
        "to bt on the fill date (`WeighTarget` + `Rebalance`, `commissions = |q|·p·bps/1e4`,",
        "`integer_positions=False`). Gaps are engine minus bt, daily net returns from the first",
        "fill on.",
        "",
        "| " + " | ".join(COLUMNS) + " |",
        "|" + "---|" * len(COLUMNS),
    ]
    for name, bps, when, c in rows:
        lines.append(
            f"| {name} | {bps} | {when} | {c.n_days} | {c.ann_gap_bp:.4f} | {c.corr:.10f} | "
            f"{c.max_abs_gap:.2e} | {c.weight_dev:.2e} | {c.max_abs_gap_bt_convention:.2e} | "
            f"{c.sizing_error:.2e} |"
        )
    lines += [
        "",
        "## Pass criterion (PLAN §2.3)",
        "",
        f"At 0 bp: annual return within {TOL_ANN_BP:g} bp/yr and daily correlation > {TOL_CORR}: "
        f"**{'pass' if ok else 'FAIL'}** for B1, B3 and B4.",
        "",
        "## Gap decomposition (PLAN §9.3)",
        "",
        "- **(a) Trade timing.** bt trades at the close of the bar on which weights appear. Fed",
        "  on the fill date, it matches the engine; fed on the order date (last row of the table),",
        "  it trades one bar early, which shows up as the max daily gap of that row.",
        "- **(b) Commission handling.** bt sizes each trade from the pre-trade value V and takes",
        "  the commission out of the trade: a position moving to a non-zero target changes by",
        "  `A/(1 ± bps/1e4)` for an amount `A = (w − u)·V` while cash pays `A`; a position closed",
        "  to zero pays its fee from the proceeds. The engine trades exactly to the target and",
        "  charges `bps·Σ|Δw|` to NAV. A replica of bt's rule (`crosscheck.bt_convention`)",
        "  matches bt to floating point (last two columns), so (b) explains the whole gap at",
        "  10 and 50 bp. bt's post-fill weights miss the target by up to the column",
        '  "Max weight vs target".',
        "  The replica always uses fill-date weights, so in the unshifted row its columns",
        "  measure the timing difference (a) instead.",
        "- **(c) Cash residuals.** None: fractional positions (`integer_positions=False`).",
        "- **(d) Floating point.** The 0 bp rows: daily gaps of order 1e-15.",
        "",
        "## Real data",
        "",
        "Not run yet: strategy returns on real data wait for the `prereg-v1` tag (rule 7,",
        "correction C17). `tests/crosscheck/test_bt.py::"
        "test_bt_matches_engine_real_research_period`",
        "runs B1, B3 and B4 on the research period at 0 bp once the tag exists.",
        "",
    ]
    out = paths.REPORTS_DIR / "crosscheck.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("\n".join(lines[11 : 12 + len(rows) + 1]))
    print(f"wrote {out}; zero-cost criterion: {'pass' if ok else 'FAIL'}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
